import { P } from './_util.mjs'
import { measureLayout, layoutChecks } from '../layout.mjs'
async function measure(t, label) {
  await t.settle()
  const m = await measureLayout(t.page)
  t.check(`${label}: real content, bounded geometry and zero overflow`, Object.values(layoutChecks(m)).every(Boolean), JSON.stringify(m))
  t.eq(`${label}: requested theme`, m.theme, label.split('-')[0])
  await t.shot(label)
}
export async function run(t) {
  for (const theme of ['dark', 'light']) {
    await t.context.addInitScript(value => localStorage.setItem('techmen:theme', value), theme)
    t.as(`${theme}: folding ships off and preview is harmless`)
    await t.open('/standing/team', { persona: 'admin', mig: 'all', reset: true, ready: '.st-tabs' })
    await t.evaluate(id => {
      window.__fx.patch('standing_records', { member_id: id, kind: 'hours', status: 'open' }, { status: 'failed', closed_on: '2026-09-27' })
      window.__fx.insert('standing_records', { member_id: id, kind: 'removal', reason: 'Short week on probation, week of 2026-09-21', status: 'proposed', opened_on: '2026-09-27' })
    }, P.student2.id)
    const before = await t.rows('standing_records')
    await t.press('.st-tab:has-text("Settings")')
    await t.waitFor('[aria-label="Automatic folding"] strong')
    t.eq('setting starts off', await t.text('[aria-label="Automatic folding"] strong'), 'Off')
    t.check('preview names Riley and the existing failure', (await t.text('[aria-label="Automatic folding"]')).includes('Riley') && (await t.text('[aria-label="Automatic folding"]')).includes('Short week on probation'), '')
    t.eq('preview changes no standing records', await t.rows('standing_records'), before)
    await measure(t, `${theme}-preview`)
    await t.press('button:has-text("Turn automatic folding on")')
    await t.waitFor('button:has-text("Turn automatic folding off")')
    t.eq('admin can turn on', (await t.rows('participation_settings'))[0].enabled, true)
    await t.press('button:has-text("Turn automatic folding off")')
    await t.waitFor('button:has-text("Turn automatic folding on")')
    t.eq('admin can turn off', (await t.rows('participation_settings'))[0].enabled, false)
    t.as(`${theme}: mentor overrides and restores`)
    await t.open('/standing/team', { persona: 'mentor', mig: 'all', ready: '[aria-label="Roster participation"] select' })
    t.eq('mentor has overrides but no Settings tab', [await t.count('[aria-label="Roster participation"]'), await t.count('.st-tab:has-text("Settings")')], [1, 0])
    await t.page.selectOption('[aria-label="Roster participation"] select', P.student2.id)
    await t.press('button:has-text("Keep member active")')
    await t.waitFor('button:has-text("Withdraw override")')
    await t.open('/standing/team', { persona: 'admin', mig: 'all', ready: '.st-tabs' })
    await t.press('.st-tab:has-text("Settings")')
    await t.waitFor('[aria-label="Automatic folding"] strong')
    t.check('mentor override excludes the candidate', (await t.text('[aria-label="Automatic folding"]')).includes('No members would fold today.'), '')
    await t.open('/standing/team', { persona: 'mentor', mig: 'all', ready: 'button:has-text("Withdraw override")' })
    await t.press('button:has-text("Withdraw override")')
    await t.waitFor(() => !document.querySelector('[aria-label="Roster participation"] .ra-list li'))
    await t.evaluate(id => {
      window.__fx.patch('profiles', { id }, { status: 'folded' })
      window.__fx.insert('member_participation', { member_id: id, keep_active: false, folded_at: new Date().toISOString(), reason: 'Short week on probation, week of 2026-09-21' })
    }, P.exempt.id)
    await t.open('/roster', { persona: 'admin', mig: 'all', ready: '[aria-label="Roster participation"] .ra-list li' })
    t.eq('folded member has own section and leaves active list', [await t.count('[aria-label="Roster participation"] button:has-text("Restore to active")'), await t.count('.roster-member:has-text("Casey")')], [1, 0])
    t.check('fold reason and date displayed', /Short week on probation[\s\S]*Folded/.test(await t.text('[aria-label="Roster participation"]')), '')
    await t.tapTargets('[aria-label="Roster participation"] button', 'participation buttons at least 44px')
    await measure(t, `${theme}-folded-roster`)
    await t.press('button:has-text("Restore to active")')
    await t.waitFor('.roster-member:has-text("Casey")')
    t.eq('one tap restores and preserves approval', (await t.rows('profiles')).filter(p => p.id === P.exempt.id).map(p => [p.status, p.approved]), [['active', true]])
    t.as(`${theme}: existing personal student review`)
    await t.evaluate(id => window.__fx.insert('member_roles', { member_id: id, role: 'student' }), P.parent.id)
    await t.open('/accounts', { persona: 'admin', mig: 'all', ready: '[aria-label="Personal email accounts"] .ra-list li' })
    t.check('legacy personal student is listed for review', (await t.text('[aria-label="Personal email accounts"]')).includes('Existing personal-email student: needs review.'), '')
    await measure(t, `${theme}-account-review`)
    const row = t.page.locator('[aria-label="Personal email accounts"] li', { hasText: P.parent.email })
    await row.locator('select').selectOption('parent')
    await row.locator('button').click()
    await t.waitText('Classification saved.')
    t.eq('admin reclassification replaces student with parent', (await t.rows('member_roles')).filter(r => r.member_id === P.parent.id && ['parent', 'student'].includes(r.role)).map(r => r.role), ['parent'])
    t.as(`${theme}: two sessions create a pending transfer`)
    await t.open('/profile', { persona: 'parent', mig: 'all', ready: '[aria-label="Summer account transfer"]' })
    await t.press('button:has-text("Generate one-time transfer code")')
    await t.waitFor('.ra-code')
    const code = await t.text('.ra-code')
    t.eq('personal session generates a 32-character code', code.length, 32)
    await t.tapTargets('[aria-label="Summer account transfer"] button', 'transfer button at least 44px')
    await measure(t, `${theme}-transfer-code`)
    await t.open('/profile', { persona: 'student2', mig: 'all', ready: '[aria-label="Summer account transfer"] input' })
    await t.page.fill('[aria-label="Summer account transfer"] input', code)
    await t.press('button:has-text("Request transfer")')
    await t.waitText('Transfer requested.')
    t.eq('request remains pending before admin action', (await t.rows('account_transfer_requests')).map(r => r.status), ['pending'])
    await measure(t, `${theme}-transfer-pending`)
    await t.open('/accounts', { persona: 'student2', mig: 'all', ready: '.st-title' })
    t.eq('student has no approval button, admin gate present', [await t.count('button:has-text("Approve transfer")'), (await t.text('.st-wrap')).includes('Admin only.')], [0, true])
    await t.open('/accounts', { persona: 'admin', mig: 'all', ready: 'button:has-text("Approve transfer")' })
    t.check('admin sees both proven account emails', (await t.text('[aria-label="Transfer approval"]')).includes(P.parent.email) && (await t.text('[aria-label="Transfer approval"]')).includes(P.student2.email), '')
    await measure(t, `${theme}-transfer-approval`)
    await t.press('button:has-text("Approve transfer")')
    await t.waitText('Transfer approved. History moved')
    t.eq('admin approval recorded', (await t.rows('account_transfer_requests')).map(r => r.status), ['approved'])
    t.as(`${theme}: access request classification`)
    await t.evaluate(() => {
      const id = window.__fx.personas.pending.id
      window.__fx.db.access_requests = window.__fx.db.access_requests.filter(r => r.email !== window.__fx.personas.pending.email)
      window.__fx.save()
      window.__fx.patch('account_classifications', { member_id: id }, { classification: 'parent', legacy: false, reason: 'Personal email with no roster role at first claim.' })
    })
    await t.open('/dashboard', { persona: 'pending', mig: 'all', ready: '[data-classification]' })
    t.check('requester sees parent classification with reason', (await t.text('[data-classification]')).includes('parent') && (await t.text('[data-classification]')).includes('Personal email with no roster role'), '')
    t.eq('request defaults to classified parent', await t.page.locator('.gate-form select').inputValue(), 'parent')
    await measure(t, `${theme}-access-classification`)
    await t.page.fill('.gate-form input[type="text"]', 'Fictional Guardian')
    await t.press('button.gate-submit')
    await t.waitText('Request sent')
    await t.open('/access-requests', { persona: 'admin', mig: 'all', ready: '.ar-access li' })
    t.check('staff sees classification and reason alongside request', (await t.text('.ar-access')).includes('Personal email with no roster role'), '')
    await measure(t, `${theme}-staff-access-classification`)
    t.as(`${theme}: setup and error states`)
    const pre = await t.evaluate(() => window.__fx.migrationNumbers.filter(m => m !== '0050').join(','))
    await t.open('/accounts', { persona: 'admin', mig: pre, reset: true, ready: '.st-title' })
    t.check('missing migration says not set up', (await t.text('.st-wrap')).includes('Not set up yet.'), '')
  }
}

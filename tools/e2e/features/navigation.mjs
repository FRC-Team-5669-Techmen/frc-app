// Global navigation: real native disclosure/dialog behavior, role visibility,
// keyboard focus, touch targets, search, chooser links and route changes.
export default {
  async run(t) {
    for (const theme of ['dark', 'light']) for (const who of ['student', 'student2', 'mentor', 'admin', 'parent']) {
      const parent = who === 'parent', staff = ['mentor', 'admin'].includes(who), approver = who === 'student2'
      t.as(`${who} ${theme}`)
      await t.open('/dashboard', { persona: who, mig: 'all', reset: true, ready: '.nav-avatar-btn' })
      await t.evaluate(theme => { localStorage.setItem('techmen:theme', theme); document.documentElement.dataset.theme = theme }, theme)
      const top = await t.texts('.navbar-links > a, .navbar-links .nav-dropdown > button')
      t.eq('short primary navigation', top, parent ? ['Home', 'Schedule', 'Team Hours'] : ['Home', 'Schedule', 'Scouting', 'Robot', 'Hours▾'])
      await t.press('.nav-avatar-btn')
      const count = await t.count('.nav-avatar-menu > .nav-dropdown-item, .nav-avatar-menu > details > summary')
      t.eq('all top-level branches, including Preferences, fit six', count, staff || approver ? 6 : 5)
      t.eq('Team admin visibility', await t.count('.nav-avatar-menu a[href="/manage"]'), staff ? 1 : 0)
      t.eq('capability-only Sign-outs visibility', await t.count('.nav-avatar-menu a[href="/signouts"]'), approver ? 1 : 0)
      await t.press(t.page.locator('.nav-menu-group > summary', { hasText: 'My record' }))
      t.eq('Handbook and Certifications are direct record links', await t.visibleCount('.nav-menu-group-items a[href="/handbook"], .nav-menu-group-items a[href="/certifications"]'), 2)
      await t.press(t.page.locator('.nav-menu-group > summary', { hasText: 'Preferences' }))
      await t.tapTargets('.nav-avatar-menu a, .nav-avatar-menu button, .nav-avatar-menu summary', 'account targets at least 44px', { everyWidth: true })
      await t.page.locator('.nav-avatar-menu a[href="/profile"]').focus()
      await t.page.keyboard.press('Escape')
      t.eq('Escape closes the menu', await t.count('.nav-avatar-menu'), 0)
      t.eq('Escape returns focus to the avatar', await t.evaluate(() => document.activeElement.matches('.nav-avatar-btn')), true)
      await t.press('.nav-avatar-btn')
      await t.press('.nav-search-btn')
      await t.waitFor('.command-palette[open]')
      t.eq('search closes the account menu', await t.count('.nav-avatar-menu'), 0)
      t.eq('search input takes focus', await t.evaluate(() => document.activeElement.matches('.command-palette input')), true)
      const paths = await t.page.locator('[data-command]').evaluateAll(els => els.map(el => el.dataset.command))
      t.check('home and profile present', paths.includes('/dashboard') && paths.includes('/profile'), `${paths.length} pages`)
      const adminPaths = ['/roster', '/feedback', '/announce', '/connector/*']
      t.eq('admin-only pages: four for admin, zero otherwise', paths.filter(p => adminPaths.includes(p)).length, who === 'admin' ? 4 : 0)
      t.eq('staff-only Team admin', paths.includes('/manage'), staff)
      t.eq('Sign-outs in search follows capability', paths.includes('/signouts'), staff || approver)
      t.eq('private tokens are never fabricated', paths.filter(p => p.includes(':token')).length, 0)
      t.eq('driver and scouting tools follow member access', paths.includes('/drivers') && paths.includes('/scouting'), !parent)
      await t.tapTargets('.nav-search-btn, .command-head button, .command-palette input, .command-result', 'search targets at least 44px', { everyWidth: true })
      await t.page.keyboard.press('End')
      t.eq('End selects the last result', await t.page.locator('[role="option"][aria-selected="true"]').getAttribute('data-command'), paths.at(-1))
      await t.page.keyboard.press('ArrowDown')
      t.eq('Down wraps to first result', await t.page.locator('[role="option"][aria-selected="true"]').getAttribute('data-command'), paths[0])
      await t.page.keyboard.press('Shift+Tab')
      t.eq('Tab stays in the native modal', await t.evaluate(() => !!document.activeElement.closest('.command-palette')), true)
      await t.page.locator('.command-palette input').fill('invented-no-such-page')
      t.eq('empty search has no options', await t.count('[data-command]'), 0)
      t.check('empty search explains recovery', (await t.text('.command-status')).includes('Try a different word'))
      await t.page.keyboard.press('Enter')
      t.eq('Enter with no result keeps search open', await t.count('.command-palette[open]'), 1)
      await t.page.keyboard.press('Escape')
      t.eq('Escape closes search', await t.count('.command-palette[open]'), 0)
      t.eq('focus returns to Search', await t.evaluate(() => document.activeElement.matches('.nav-search-btn')), true)
      await t.page.keyboard.press('Control+k')
      await t.waitFor('.command-palette[open]')
      await t.page.locator('.command-palette input').fill('my profile')
      await t.page.keyboard.press('Enter')
      await t.waitFor('.profile-theme-card')
      t.eq('keyboard result navigates to the real profile', new URL(t.page.url()).pathname, '/profile')
      t.eq('navigation closes the palette', await t.count('.command-palette[open]'), 0)
      await t.page.keyboard.press('Meta+k')
      await t.waitFor('.command-palette[open]')
      await t.page.locator('.command-palette input').fill(parent ? 'emergency' : 'drivers')
      const target = parent ? '/emergency-info' : '/drivers'
      await t.press(t.page.locator(`[data-command="${target}"]`))
      await t.page.waitForURL(url => url.pathname === target)
      t.eq('touch/click result reaches the role tool', new URL(t.page.url()).pathname, target)
      await t.noHScroll()
    }
    t.as('matching event context')
    await t.open('/scouting/16000000-0000-4000-8000-000000000001', { persona: 'student', ready: '.nav-search-btn' })
    await t.press('.nav-search-btn')
    await t.page.locator('.command-palette input').fill('pick board')
    await t.press('[data-command="/scouting/:eventId/board"]')
    await t.page.waitForURL(url => url.pathname.endsWith('/board'))
    t.check('Pick board opens for the current event', new URL(t.page.url()).pathname === '/scouting/16000000-0000-4000-8000-000000000001/board')
    await t.open('/dashboard', { persona: 'student', mig: 'none', ready: '.nav-avatar-btn' })
    await t.press('.nav-search-btn')
    await t.waitFor('.command-palette[open]')
    t.eq('missing capability RPC does not advertise sign-outs', await t.count('[data-command="/signouts"]'), 0)
    t.eq('basic navigation still works without migrations', await t.count('[data-command="/profile"]'), 1)
  },
}

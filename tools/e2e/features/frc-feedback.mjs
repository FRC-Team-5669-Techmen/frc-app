import { P } from './_util.mjs'
import { seedForty } from './scouting-teams.mjs'
const EVENT = '16000000-0000-4000-8000-000000000001'
const route = `/scouting/${EVENT}`
const pauseId = '46000000-0000-4000-8000-000000000001'
const logId = '46000000-0000-4000-8000-000000000002'
const base = new Date('2026-10-01T23:00:00Z')

export default { async run(t) {
  for (const theme of ['dark', 'light']) {
    await t.context.addInitScript(value => localStorage.setItem('techmen:theme', value), theme)
    await t.context.clock.setFixedTime(base)
    t.as(`${theme} weekly hours and pause`)
    await t.open('/dashboard', { persona: 'student', mig: 'all', reset: true, ready: '.mb-you' })
    await t.evaluate(({ uid, pauseId, logId }) => {
      const fx = window.__fx, now = Date.now()
      fx.db.attendance_events = fx.db.attendance_events.filter(r => r.user_id !== uid)
      fx.db.attendance_events.push({ id: pauseId, user_id: uid, type: 'in', event_time: new Date(now - 3 * 3600000).toISOString(), category: 'build', verified: false, manual_entry: false, method: 'nfc', pauses: [] })
      fx.db.logged_hours = fx.db.logged_hours.filter(r => r.member_id !== uid)
      fx.db.logged_hours.push({ id: logId, member_id: uid, date: '2026-10-01', hours: 1.5, type: 'outreach', description: 'Invented test work', status: 'pending' })
      fx.save()
    }, { uid: P.student.id, pauseId, logId })
    await t.open('/dashboard', { ready: '[data-weekly-hours]' })
    t.eq('pending hours excluded; current session counts', await t.text('[data-weekly-hours] .mb-stat-value'), '3h 0m')
    await t.evaluate(id => { window.__fx.patch('logged_hours', { id }, { status: 'verified' }); window.__fx.save() }, logId)
    await t.open('/dashboard', { ready: '[data-weekly-hours]' })
    t.eq('verification counts the worked date in this LA week', await t.text('[data-weekly-hours] .mb-stat-value'), '4h 30m')
    await t.press(t.page.getByRole('button', { name: 'Pause hours', exact: true }))
    await t.waitFor('[data-session-paused="true"]')
    await t.advanceTime(30 * 60000)
    await t.open('/dashboard', { ready: '[data-session-paused="true"]' })
    t.eq('paused half-hour did not inflate the weekly total', await t.text('[data-weekly-hours] .mb-stat-value'), '4h 30m')
    t.check('paused time is shown and member remains checked in', (await t.text('.mb-pause')).includes('30m') && (await t.text('.mb-status')).includes('Checked in'))
    t.eq('pause did not write a checkout', (await t.rows('attendance_events')).filter(r => r.user_id === P.student.id && r.type === 'out').length, 0)
    await t.press(t.page.getByRole('button', { name: 'Resume hours', exact: true }))
    await t.waitFor('[data-session-paused="false"]')
    await t.advanceTime(15 * 60000)
    await t.open('/dashboard', { ready: '[data-weekly-hours]' })
    t.eq('resumed time counts again, paused time stays excluded', await t.text('[data-weekly-hours] .mb-stat-value'), '4h 45m')
    await t.press(t.page.getByRole('button', { name: 'Check Out', exact: true }))
    t.eq('paused/resumed build session still asks a mentor to sign out', await t.page.getByRole('button', { name: 'Ask to sign out', exact: true }).count(), 1)
    await t.noHScroll(); await t.shot(`${theme}-dashboard`)

    await t.press(t.page.getByRole('button', { name: 'Pause hours', exact: true }))
    await t.waitFor('[data-session-paused="true"]')
    await t.page.locator('.so-form textarea').fill('Completed invented wiring task')
    await t.page.locator('.so-check input').check()
    await t.press(t.page.getByRole('button', { name: 'Ask to sign out', exact: true }))
    await t.waitText('Sign-out waiting for approval')
    const request = (await t.rows('signout_requests')).find(r => r.member_id === P.student.id && r.status === 'pending')
    t.check('paused member still requests approval', !!request)
    await t.advanceTime(5 * 60000)
    await t.open('/signouts', { persona: 'mentor', ready: '.sop-wrap' })
    t.check('mentor sees paused member present', (await t.text(`[data-member="${P.student.id}"]`)).includes('Hours paused'))
    await t.press(t.page.locator(`[data-request="${request.id}"] button.sop-name`))
    await t.settle()
    const after = (await t.rows('attendance_events')).filter(r => r.user_id === P.student.id)
    t.eq('one approved checkout, pause ended at checkout', [after.filter(r => r.type === 'out').length, after.find(r => r.id === pauseId)?.pauses.at(-1)?.end !== null], [1, true])
    await t.open('/dashboard', { persona: 'student', ready: '.mb-you' })
    t.eq('waiting while paused added no weekly hours', await t.text('[data-weekly-hours] .mb-stat-value'), '4h 45m')
    await t.open('/standing', { ready: '[data-card="week"]' })
    t.check('standing weekly total counts verified FRC logs and excludes pauses', (await t.text('[data-card="week"] .st-big')).includes('4h 45m'))
    await t.open('/my-hours', { ready: '.mh-body' })
    t.check('hours history exposes paused time', (await t.text('.mh-body')).includes('35m paused, excluded'))
    await t.noHScroll(); await t.shot(`${theme}-hours`)

    t.as(`${theme} direct sign-out pause guidance`)
    for (const [persona, uid, category] of [['student', P.student.id, 'volunteer'], ['mentor', P.mentor.id, 'build']]) {
      await t.open('/dashboard', { persona, mig: 'all', reset: true, ready: '.mb-you' })
      await t.evaluate(({ uid, category }) => {
        const fx = window.__fx
        fx.db.attendance_events = fx.db.attendance_events.filter(r => r.user_id !== uid)
        fx.db.attendance_events.push({ id: '47000000-0000-4000-8000-000000000003', user_id: uid, type: 'in', event_time: new Date(Date.now() - 2 * 3600000).toISOString(), category, method: 'nfc', pauses: [] })
        fx.save()
      }, { uid, category })
      await t.open('/dashboard', { ready: '[data-session-paused="false"]' })
      const guidance = await t.text('.mb-pause')
      t.check(`${persona} ${category}: visible pause guidance respects direct sign-out`,
        await t.page.getByRole('button', { name: 'Pause hours', exact: true }).isVisible()
        && await t.page.getByRole('button', { name: 'Check Out', exact: true }).isVisible()
        && guidance.includes('Pause for non-FRC work.') && !guidance.includes('until a mentor approves leaving'), guidance)
      await t.noHScroll(); await t.shot(`${theme}-${persona}-${category}-pause-guidance`)
    }

    t.as(`${theme} withdrawn probation and mentor explanation`)
    await t.open('/standing', { persona: 'student2', mig: 'all', reset: true, ready: '.st-wrap' })
    t.eq('member has no staff evidence control', await t.page.getByRole('button', { name: 'Why this record?', exact: true }).count(), 0)
    await t.evaluate(() => { for (const r of window.__fx.db.standing_records) r.status = 'dismissed'; window.__fx.save() })
    await t.open('/standing', { ready: '[data-card="letter"]' })
    const cleanLine = t.page.locator('[data-card="letter"] li').filter({ hasText: 'A full season with no meetings or hours probation' })
    t.check('withdrawn probation meets the season-clean line', (await cleanLine.textContent()).trim().startsWith('✓') && !(await cleanLine.getAttribute('class') ?? '').includes('bad'))
    await t.open(`/standing?member=${P.student2.id}`, { persona: 'mentor', ready: '.st-wrap' })
    await t.press(t.page.getByRole('button', { name: 'Why this record?', exact: true }).first())
    await t.waitFor('[data-standing-evidence]')
    await t.waitText('Reconstructed from current records')
    t.check('mentor sees evaluated record and original-data limitation', (await t.text('[data-standing-evidence]')).includes('Evaluated week:'))
    await t.noHScroll(); await t.shot(`${theme}-standing`)

    t.as(`${theme} batteries`)
    await t.open('/batteries', { persona: 'student', mig: 'all', reset: true, ready: '.ba-card' })
    await t.evaluate(() => {
      const fx = window.__fx, b = fx.db.batteries.find(b => b.label === 'B01')
      for (let i = 0; i < 3; i++) fx.db.battery_runs.push({ id: `46000000-0000-4000-8000-00000000001${i}`, battery_id: b.id, member_id: b.created_by, ran_at: new Date(Date.now() - i * 60000).toISOString(), kind: 'match', performance: 5, brownout: 'no', voltage_before: 12.9, resistance_mohm: 15 })
      fx.save()
    })
    await t.open('/batteries', { ready: '.ba-card' })
    t.eq('measured Good battery leads the board', (await t.texts('.ba-card .ba-label'))[0], 'B01')
    t.eq('Good has a marker; unknown B05 has none', [await t.count('.ba-card[data-battery="B01"] .ba-pill-good'), await t.count('.ba-card[data-battery="B05"] .ba-pill-good')], [1, 0])
    await t.press(t.page.locator('.ba-card[data-battery="B01"] .ba-good summary'))
    t.check('tap reveals the performance rule', await t.page.locator('.ba-card[data-battery="B01"] .ba-good p').isVisible())
    t.check('hover has the same rule', (await t.page.locator('.ba-card[data-battery="B01"] .ba-good summary').getAttribute('title')).includes('4/5'))
    await t.noHScroll(); await t.shot(`${theme}-batteries`)

    t.as(`${theme} full-screen scouting and sortable dense event`)
    await t.open('/scouting', { persona: 'mentor', mig: 'all', reset: true, ready: '.sc-wrap' })
    const listWidth = await t.page.locator('.sc-wrap').evaluate(el => el.getBoundingClientRect().width)
    t.check('event list uses available viewport', t.isPhone ? listWidth <= 375 : listWidth >= Number(t.width) - 2, `${listWidth}px`)
    await t.noHScroll(); await t.shot(`${theme}-scouting-list`)
    await t.open(route, { persona: 'mentor', ready: '.sc-wrap' })
    await t.evaluate(seedForty, { event: EVENT, mentor: P.mentor.id, student2: P.student2.id })
    await t.open(route, { persona: 'mentor', ready: '.sc-wrap' })
    await t.press(t.page.getByRole('tab', { name: 'Teams', exact: true }))
    await t.waitFor('[data-team-table]')
    t.eq('all event teams have one row', await t.count('.sc-team-row'), 44)
    const m = await t.page.evaluate(() => {
      const wrap = document.querySelector('.sc-wrap'), box = document.querySelector('[data-team-table]'), row = document.querySelector('.sc-team-row'), head = document.querySelector('.sc-team-table th')
      return { width: wrap.getBoundingClientRect().width, row: row.getBoundingClientRect().height, height: box.clientHeight, scrollHeight: box.scrollHeight, top: box.getBoundingClientRect().top, sticky: getComputedStyle(head).position, theme: document.documentElement.dataset.theme, overflow: document.documentElement.scrollWidth-innerWidth }
    })
    t.eq('theme is painted', m.theme, theme)
    t.eq('0px document overflow', m.overflow, 0)
    t.check('event fills available desk width', t.isPhone ? m.width <= 375 : m.width >= Number(t.width) - 2, JSON.stringify(m))
    if (!t.isPhone) t.check('analysis begins without a screen of introduction', m.top < 600, JSON.stringify(m))
    t.check('staff desktop is dense, phone keeps touch targets', t.isPhone ? m.row >= 44 : m.row <= 30, JSON.stringify(m))
    t.check('event scroll is bounded with sticky headers', m.height <= (t.isPhone ? 812 : 900) * .71 && m.scrollHeight > m.height && m.sticky === 'sticky', JSON.stringify(m))
    for (const th of await t.page.locator('.sc-team-table thead th:visible').all()) {
      const key = await th.getAttribute('data-col')
      await t.press(th.locator('button')); const first = await th.getAttribute('aria-sort')
      await t.press(th.locator('button')); const second = await th.getAttribute('aria-sort')
      t.check(`${key} sorts in both directions`, ['ascending','descending'].includes(first) && second !== first)
    }
    await t.page.getByLabel('Minimum FUEL', { exact: true }).fill('50')
    const fuel = await t.texts('.sc-team-row [data-col="fuel"]')
    t.check('confirmed FUEL filter excludes unknown and lower values', fuel.length > 0 && fuel.length < 44 && fuel.every(v => Number(v) >= 50), `${fuel.length} rows`)
    await t.press(t.page.getByRole('button', { name: 'Clear filters', exact: true }))
    t.eq('clearing filters restores every team', await t.count('.sc-team-row'), 44)
    await t.page.locator('[data-team-table]').evaluate(el => { el.scrollTop = 400 })
    const sticky = await t.page.evaluate(() => { const box = document.querySelector('[data-team-table]').getBoundingClientRect(), th = document.querySelector('.sc-team-table th').getBoundingClientRect(); return Math.abs(box.top - th.top) < 3 })
    t.check('header stays at the scroll container top', sticky)
    await t.noHScroll(); await t.shot(`${theme}-scouting-event`)
    if (!t.isPhone) {
      const style = await t.page.addStyleTag({ content: ':root .sc-wrap { max-width: 80rem !important; } .sc-team-table th { position: static !important; }' })
      const bad = await t.page.evaluate(() => (innerWidth <= 1280 || document.querySelector('.sc-wrap').getBoundingClientRect().width < innerWidth - 2) && getComputedStyle(document.querySelector('.sc-team-table th')).position !== 'sticky')
      t.check('old narrow/nonsticky geometry is caught by the measurement', bad)
      await style.evaluate(el => el.remove())
    }
    await t.press(t.page.getByRole('tab', { name: 'Pick lists', exact: true }))
    t.check('automatic ranking remains reachable', await t.page.locator('[data-board-link]').isVisible())
    if (t.isPhone) t.eq('no hand tier rating buttons on phones', await t.visibleCount('.sc-rate-buttons button'), 0)
    t.eq('manual tier editor follows desktop scope', await t.page.getByRole('button', { name: 'My list', exact: true }).isVisible(), !t.isPhone)
  }
} }

#!/usr/bin/env node
// Prints the indexes over `docs/history/`, from the entries' own front matter.
// Nothing it prints is committed: a committed index is a single line every
// session edits, which is the write point the split removed. Regenerate it
// whenever you want one; `grep -r` over the directory is the primary way to
// find an entry, and the front matter carries everything these indexes key on.
//
//   npm run history:index                 -- print to stdout
//   npm run history:index -- --out <path> -- write a file (gitignored)
//
// The migration index is INVERTED from each entry's `migrations:` list. There
// is no migration -> entry table to maintain, and there must not be: it is a
// many-to-many mapping and a second copy of it is the copy that goes stale.
//
// Ported from pina-hash/idea-app docs/history/_tools/index.mjs. Two differences,
// both from this repo's own shape: entries carry `commits` (this repo's history
// predates the record, so a bundle is located by its commit rather than by a
// branch that was deleted), and the migration list is filenames rather than
// numbers, because SQL here is unnumbered under `supabase/` (see
// `supabase/migrations/README.md` for the rule from this bundle forward).

import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { readEntries } from './front-matter.mjs';

const MIGRATIONS_DIR = new URL('../../../supabase/migrations/', import.meta.url).pathname;
const LEGACY_SQL_DIR = new URL('../../../supabase/', import.meta.url).pathname;

// The order groups are printed in. A subsystem an entry names that is not
// listed here still prints, at the end, so a new subsystem is never silently
// dropped -- it is simply unsorted until someone adds it.
const GROUP_ORDER = [
  'Hours and attendance',
  'Jobs',
  'Schedule',
  'Surveys',
  'Feedback',
  'Member application',
  'Roster and access',
  'Subteams',
  'Navigation',
  'Theme',
  'Design system',
  'Discord',
  'Supabase functions',
  'CI',
];

const entries = readEntries();

// Record order for the pre-split archive (1 = newest, as the paragraph read),
// so the archive prints newest-first exactly as CLAUDE.md did; date then
// filename for everything after it, which is where every new entry lands.
const position = (e) =>
  Number.isInteger(e.record_order)
    ? [0, e.record_order, '']
    : [1, 0, `${e.date} ${e.file}`];
const byPosition = (a, b) => {
  const [ak, an, as] = position(a);
  const [bk, bn, bs] = position(b);
  return ak - bk || an - bn || as.localeCompare(bs);
};
entries.sort(byPosition);

const link = (e) => `[${e.title}](${e.file})`;
const out = [];
const w = (s = '') => out.push(s);

w('# Index of `docs/history/`');
w();
w('GENERATED by `npm run history:index` from the front matter of every file in');
w('this directory. Do not commit it and do not edit it: it is rebuilt from the');
w('entries, and the entries are the record.');
w();
w(`${entries.length} entries. Generated ${new Date().toISOString().slice(0, 10)}.`);
w();
w('---');
w();

// --- 1. by subsystem --------------------------------------------------------
w('## Index by subsystem');
w();
const groups = new Map();
for (const e of entries) {
  for (const g of e.subsystems.length ? e.subsystems : ['(no subsystem)']) {
    if (!groups.has(g)) groups.set(g, []);
    groups.get(g).push(e);
  }
}
const known = GROUP_ORDER.filter((g) => groups.has(g));
const rest = [...groups.keys()].filter((g) => !GROUP_ORDER.includes(g)).sort();
for (const g of [...known, ...rest]) {
  w(`### ${g}`);
  w();
  for (const e of groups.get(g)) w(`- ${e.date} ${link(e)}`);
  w();
}

// --- 2. by migration --------------------------------------------------------
w('---');
w();
w('## Index by SQL file');
w();
w("Inverted from each entry's `migrations:` list. A file with no entry of its own");
w('is documented inside the one listed. Files are named, not numbered: everything');
w('under `supabase/*.sql` predates numbering and is frozen where it is (see');
w('`supabase/migrations/README.md`).');
w();
w('| File | On disk | Documented in |');
w('|---|---|---|');
const byMigration = new Map();
for (const e of entries) {
  for (const m of e.migrations) {
    if (!byMigration.has(m)) byMigration.set(m, []);
    byMigration.get(m).push(e);
  }
}
// Every row comes from disk as well as from what the entries claim, so a SQL
// file nobody documented still gets a row and says so, and a filename an entry
// claims that has no file gets a row too.
const onDisk = new Set();
for (const dir of [LEGACY_SQL_DIR, MIGRATIONS_DIR]) {
  if (!existsSync(dir)) continue;
  for (const f of readdirSync(dir).sort()) if (f.endsWith('.sql')) onDisk.add(f);
}
const names = [...new Set([...onDisk, ...byMigration.keys()])].sort();
let undocumented = 0;
for (const m of names) {
  const docs = byMigration.get(m);
  if (!docs) undocumented += 1;
  const where = docs
    ? docs.sort(byPosition).map(link).join('; ')
    : '_(not documented in the record -- read the SQL)_';
  w(`| \`${m}\` | ${onDisk.has(m) ? 'yes' : '_(no file on disk)_'} | ${where} |`);
}
w();
w(`${names.length} SQL files, ${undocumented} of them documented by no entry.`);
w();

const text = out.join('\n');
const flag = process.argv.indexOf('--out');
if (flag >= 0) {
  const path = process.argv[flag + 1] || new URL('../_generated/INDEX.md', import.meta.url).pathname;
  writeFileSync(path, text);
  console.error(`wrote ${path} (${entries.length} entries, ${names.length} SQL files)`);
} else {
  process.stdout.write(text);
}
